-- =========================================
-- 1. SEATS TABLE
-- =========================================

CREATE TABLE IF NOT EXISTS seats (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_name VARCHAR(100) NOT NULL UNIQUE,
    seat_type VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- =========================================
-- 2. RESERVATIONS TABLE
-- =========================================

CREATE TABLE IF NOT EXISTS reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_name VARCHAR(100) NOT NULL,
    guest_email VARCHAR(255),
    seat_id INTEGER NOT NULL,
    reservation_date DATE NOT NULL,
    reservation_start_time TIME NOT NULL,
    reservation_end_time TIME NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reservation_seat
        FOREIGN KEY (seat_id)
        REFERENCES seats(id),

    CONSTRAINT unique_booking
        UNIQUE (seat_id, reservation_date, reservation_start_time)
);

